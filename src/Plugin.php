<?php

declare(strict_types=1);

namespace Coverage;

use Coverage\Contract\HasHooks;

defined('ABSPATH') || exit;

final class Plugin
{
    private static ?self $instance = null;

    private Container $container;

    private bool $booted = false;

    private function __construct()
    {
        $this->container = new Container();
        (require __DIR__ . '/../config/services.php')($this->container);
    }

    public static function instance(): self
    {
        return self::$instance ??= new self();
    }

    public function container(): Container
    {
        return $this->container;
    }

    public function boot(): void
    {
        if ($this->booted) {
            return;
        }
        $this->booted = true;

        // Bundled translations (languages/), used until wp.org language packs exist.
        load_plugin_textdomain('coverwick', false, dirname(plugin_basename(PLUGIN_FILE)) . '/languages');

        $this->container->get(Migrator::class)->maybeMigrate();

        /** @var array<class-string<HasHooks>> $hooks */
        $hooks = require __DIR__ . '/../config/hooks.php';
        foreach ($hooks as $id) {
            $service = $this->container->get($id);
            if ($service instanceof HasHooks) {
                $service->registerHooks();
            }
        }

        /**
         * Fires after the plugin has fully booted. PRO companions hook here.
         *
         * @param Plugin $plugin The booted plugin instance.
         */
        do_action('coverage/booted', $this);
    }
}
